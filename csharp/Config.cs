using System.Security.Cryptography;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace MicBridge;

public sealed class Config
{
    /// <summary>"host" (the streamed PC that receives the mic) or "client" (the laptop whose mic is sent).</summary>
    public string Mode { get; set; } = "";

    /// <summary>Client only: address of the host PC (IP or hostname).</summary>
    public string Host { get; set; } = "";

    /// <summary>UDP port used on both ends. Stays clear of Sunshine's 47984-48010 range.</summary>
    public int Port { get; set; } = 48020;

    /// <summary>Shared 256-bit key, base64. Both ends must have the same one. Generated by the host on first run.</summary>
    public string Key { get; set; } = "";

    /// <summary>Client: substring of the microphone name to capture. Empty = Windows default communications mic.</summary>
    public string MicDevice { get; set; } = "";

    /// <summary>Host: substring of the playback device that feeds the virtual mic. Empty = auto (VB-Cable, then Steam Streaming Microphone).</summary>
    public string OutputDevice { get; set; } = "";

    /// <summary>Opus bitrate in bits per second. 24000-64000 are sensible for voice.</summary>
    public int Bitrate { get; set; } = 40000;

    /// <summary>Client: only send while a Moonlight process is running.</summary>
    public bool FollowMoonlight { get; set; } = true;

    /// <summary>Client: process name (without .exe) that marks a stream as active.</summary>
    public string MoonlightProcess { get; set; } = "Moonlight";

    /// <summary>Host: jitter cushion in milliseconds. Higher = more robust to network jitter, more latency.</summary>
    public int JitterMs { get; set; } = 60;

    /// <summary>Client: start with the mic muted.</summary>
    public bool StartMuted { get; set; } = false;

    [JsonIgnore] public string Path { get; set; } = "";

    private static readonly JsonSerializerOptions JsonOpts = new()
    {
        WriteIndented = true,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        PropertyNameCaseInsensitive = true,
        Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping, // keep "+" in keys readable
    };

    /// <summary>Directory for config + log: next to the exe if writable, else %LOCALAPPDATA%\MicBridge.</summary>
    public static string DataDir()
    {
        var exeDir = AppContext.BaseDirectory;
        try
        {
            var probe = System.IO.Path.Combine(exeDir, ".write-test");
            File.WriteAllText(probe, "");
            File.Delete(probe);
            return exeDir;
        }
        catch
        {
            var dir = System.IO.Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "MicBridge");
            Directory.CreateDirectory(dir);
            return dir;
        }
    }

    public static string DefaultPath() => System.IO.Path.Combine(DataDir(), "micbridge.json");

    public static Config Load(string path)
    {
        Config cfg;
        if (File.Exists(path))
            cfg = JsonSerializer.Deserialize<Config>(File.ReadAllText(path), JsonOpts) ?? new Config();
        else
            cfg = new Config();
        cfg.Path = path;
        return cfg;
    }

    public void Save() => File.WriteAllText(Path, JsonSerializer.Serialize(this, JsonOpts));

    public static string NewKey() => Convert.ToBase64String(RandomNumberGenerator.GetBytes(32));

    public byte[] KeyBytes()
    {
        try
        {
            var k = Convert.FromBase64String(Key.Trim());
            if (k.Length == 32) return k;
        }
        catch { }
        throw new InvalidOperationException("Key is missing or not a valid 32-byte base64 key. Copy it from the host (tray menu > Copy pairing key).");
    }
}
