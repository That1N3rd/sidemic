//! sidemic.json. Same schema as the C# version, so the two can share a config file.

use anyhow::{Context, Result, bail};
use base64::Engine;
use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};

#[derive(Serialize, Deserialize, Clone, Debug)]
#[serde(rename_all = "camelCase", default)]
pub struct Config {
    /// "host" (the streamed PC that receives the mic) or "client" (the laptop whose mic is sent).
    pub mode: String,
    /// Client only: address of the host PC (IP or hostname).
    pub host: String,
    /// UDP port used on both ends. Stays clear of Sunshine's 47984-48010 range.
    pub port: u16,
    /// Shared 256-bit key, base64. Both ends must have the same one. Generated by the host on first run.
    pub key: String,
    /// Client: substring of the microphone name to capture. Empty = Windows default mic.
    pub mic_device: String,
    /// Host: substring of the playback device feeding the virtual mic. Empty = auto (VB-Cable, then Steam Streaming Microphone).
    pub output_device: String,
    /// Opus bitrate in bits per second. 24000-64000 are sensible for voice.
    pub bitrate: i32,
    /// Client: only send while a Moonlight process is running.
    pub follow_moonlight: bool,
    /// Client: process name (without .exe) that marks a stream as active.
    pub moonlight_process: String,
    /// Host: jitter cushion in milliseconds. Higher = more robust to jitter, more latency.
    pub jitter_ms: u32,
    /// Client: start with the mic muted.
    pub start_muted: bool,
    #[serde(skip)]
    pub path: PathBuf,
}

impl Default for Config {
    fn default() -> Self {
        Self {
            mode: String::new(),
            host: String::new(),
            port: 48020,
            key: String::new(),
            mic_device: String::new(),
            output_device: String::new(),
            bitrate: 40000,
            follow_moonlight: true,
            moonlight_process: "Moonlight".into(),
            jitter_ms: 60,
            start_muted: false,
            path: PathBuf::new(),
        }
    }
}

/// Directory for config + log: next to the exe if writable, else %LOCALAPPDATA%\SideMic.
pub fn data_dir() -> PathBuf {
    let exe_dir = std::env::current_exe()
        .ok()
        .and_then(|p| p.parent().map(Path::to_path_buf))
        .unwrap_or_else(|| PathBuf::from("."));
    let probe = exe_dir.join(".write-test");
    if std::fs::write(&probe, b"").is_ok() {
        let _ = std::fs::remove_file(&probe);
        return exe_dir;
    }
    let base = std::env::var_os("LOCALAPPDATA").map(PathBuf::from).unwrap_or(exe_dir);
    let dir = base.join("SideMic");
    let _ = std::fs::create_dir_all(&dir);
    dir
}

pub fn default_path() -> PathBuf {
    let dir = data_dir();
    let p = dir.join("sidemic.json");
    // Older builds were called MicBridge; keep reading their config until the user saves under the new name.
    let legacy = dir.join("micbridge.json");
    if !p.exists() && legacy.exists() { legacy } else { p }
}

impl Config {
    pub fn load(path: &Path) -> Result<Config> {
        let mut cfg: Config = if path.exists() {
            let text = std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
            serde_json::from_str(&text).with_context(|| format!("parsing {}", path.display()))?
        } else {
            Config::default()
        };
        cfg.path = path.to_path_buf();
        Ok(cfg)
    }

    pub fn save(&self) -> Result<()> {
        let text = serde_json::to_string_pretty(self)?;
        std::fs::write(&self.path, text).with_context(|| format!("writing {}", self.path.display()))
    }

    pub fn new_key() -> String {
        let bytes: [u8; 32] = rand::random();
        base64::engine::general_purpose::STANDARD.encode(bytes)
    }

    pub fn key_bytes(&self) -> Result<[u8; 32]> {
        if let Ok(v) = base64::engine::general_purpose::STANDARD.decode(self.key.trim()) {
            if v.len() == 32 {
                return Ok(v.try_into().unwrap());
            }
        }
        bail!("Key is missing or not a valid 32-byte base64 key. Copy it from the host (tray menu > Copy pairing key).")
    }
}
